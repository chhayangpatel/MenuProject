// One-off helper: generates supabase/seed.sql — an upsert of menu_snapshots
// for every restaurant, mirroring the Worker's syncMenuSnapshot() shape
// ({id, price, available, variants:[{id, priceModifier}]}).
// Run: node scripts/gen-snapshots-seed.mjs
import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const restaurantsDir = path.join(root, "restaurants");
const dirs = fs
  .readdirSync(restaurantsDir, { withFileTypes: true })
  .filter((d) => d.isDirectory() && d.name !== "_template");

let sql = `-- ============================================================================
-- seed.sql (generated by scripts/gen-snapshots-seed.mjs)
-- One-time seed for local testing: upserts one menu_snapshots row per
-- restaurant from its config.json. Run AFTER 001_ordering_tables.sql.
-- Paste into Supabase Dashboard -> SQL Editor -> Run.
-- ============================================================================\n\n`;

let count = 0;
for (const dir of dirs) {
  let config;
  try {
    config = JSON.parse(
      fs.readFileSync(path.join(restaurantsDir, dir.name, "config.json"), "utf-8"),
    );
  } catch {
    continue;
  }
  const slug = config.slug || dir.name;
  const items = (config.menu ?? []).flatMap((cat) =>
    (cat.items ?? []).map((item) => ({
      id: item.id,
      price: item.price,
      available: item.available !== false,
      variants: (item.variants ?? []).map((v) => ({
        id: v.id,
        priceModifier: v.priceModifier,
      })),
    })),
  );
  const json = JSON.stringify(items).replace(/'/g, "''");
  sql += `-- ${config.name?.trim() || slug} (${items.length} items)\n`;
  sql += `insert into menu_snapshots (restaurant_slug, items, updated_at) values (\n  '${slug}',\n  '${json}'::jsonb,\n  now()\n)\non conflict (restaurant_slug) do update set items = excluded.items, updated_at = now();\n\n`;
  count++;
}

const outPath = path.join(root, "supabase", "seed.sql");
fs.writeFileSync(outPath, sql, "utf-8");
console.log(`Wrote ${outPath} with ${count} menu_snapshots upsert(s).`);
